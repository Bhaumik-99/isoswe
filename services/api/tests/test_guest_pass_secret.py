"""Tests for Guest Pass HMAC Secret Provisioning & Secrets Manager Hydration

Verifies:
1. CDK / Secrets Manager JSON payload correctly hydrates GUEST_PASS_HMAC_SECRET into settings.
2. GuestPassService._hmac_key() enforces minimum 32-character secret length in staging/production.
3. Missing or short secret raises HTTP 500 AppException(code='GUEST_PASS_SECRET_NOT_CONFIGURED').
4. Valid provisioned secret (>=32 chars) generates deterministic HMAC-SHA256 digests.
"""

import json
import uuid
from unittest.mock import MagicMock, patch

import pytest

from app.core.config import Settings, settings
from app.core.errors import AppException
from app.domains.visitors.pass_service import (
    MIN_PRODUCTION_SECRET_LENGTH,
    GuestPassService,
)


def test_hmac_secret_length_enforcement_in_production(monkeypatch: pytest.MonkeyPatch) -> None:
    """In production/staging, GUEST_PASS_HMAC_SECRET must have at least 32 characters or fail with HTTP 500."""
    monkeypatch.setattr(settings, "ENVIRONMENT", "production")

    # 1. Missing secret (empty string)
    monkeypatch.setattr(settings, "GUEST_PASS_HMAC_SECRET", "")
    with pytest.raises(AppException) as exc_info:
        GuestPassService._hmac_key()
    assert exc_info.value.status_code == 500
    assert exc_info.value.code == "GUEST_PASS_SECRET_NOT_CONFIGURED"

    # 2. Short secret (< 32 characters)
    monkeypatch.setattr(settings, "GUEST_PASS_HMAC_SECRET", "too-short-secret-12345")
    with pytest.raises(AppException) as exc_info:
        GuestPassService._hmac_key()
    assert exc_info.value.status_code == 500
    assert exc_info.value.code == "GUEST_PASS_SECRET_NOT_CONFIGURED"

    # 3. Valid automated secret (64 characters, as generated by CDK Secrets Manager)
    valid_secret = "a" * 64
    monkeypatch.setattr(settings, "GUEST_PASS_HMAC_SECRET", valid_secret)
    key = GuestPassService._hmac_key()
    assert key == valid_secret.encode("utf-8")
    assert len(key) >= MIN_PRODUCTION_SECRET_LENGTH


def test_secrets_manager_hydration_populates_guest_pass_hmac_secret(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Verifies that hydrate_aws_secrets extracts GUEST_PASS_HMAC_SECRET from AWS Secrets Manager JSON payload."""
    secret_payload = {
        "DATABASE_URL": "postgresql+psycopg://app_user:pass@db.internal:5432/township_ops",
        "SUPABASE_URL": "https://xyzcompany.supabase.co",
        "GUEST_PASS_HMAC_SECRET": "d" * 64,
    }

    mock_client = MagicMock()
    mock_client.get_secret_value.return_value = {
        "SecretString": json.dumps(secret_payload),
    }

    with patch("boto3.client", return_value=mock_client):
        hydrated = Settings.hydrate_aws_secrets(
            {
                "ENVIRONMENT": "production",
                "DATABASE_SECRET_NAME": "township-supabase-credentials-prod",
                "AWS_REGION": "ap-south-1",
            }
        )

    assert hydrated["GUEST_PASS_HMAC_SECRET"] == secret_payload["GUEST_PASS_HMAC_SECRET"]
    assert len(hydrated["GUEST_PASS_HMAC_SECRET"]) == 64
    assert hydrated["DATABASE_URL"] == secret_payload["DATABASE_URL"]
    assert hydrated["SUPABASE_URL"] == secret_payload["SUPABASE_URL"]


def test_guest_pass_hash_generation_with_provisioned_secret(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Verifies that hashing a guest pass code with the provisioned secret produces a valid 64-hex-char digest."""
    monkeypatch.setattr(settings, "ENVIRONMENT", "production")
    monkeypatch.setattr(
        settings,
        "GUEST_PASS_HMAC_SECRET",
        "d6f8a9e2c1b47035e89a421bc0879e612456789abcdef0123456789abcdef01",
    )

    society_id = uuid.uuid4()
    code = "GP-ABCD-EFGH-JKMN"
    digest = GuestPassService.hash_pass_code(code, society_id)

    assert isinstance(digest, str)
    assert len(digest) == 64
    assert all(c in "0123456789abcdef" for c in digest)
